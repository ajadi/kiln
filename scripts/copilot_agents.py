"""Write Kiln's roles as GitHub Copilot CLI agents (plugins/kiln/copilot/agents/). Stdlib only.

  python copilot_agents.py           # regenerate copilot/agents/<role>.md
  python copilot_agents.py --check   # exit 1 if they differ from agents/*.md (tests, release)

Copilot reads the plugin through .github/plugin/plugin.json, whose `agents` points here, so
each role keeps its id `kiln:<role>`. The files are the roles as they are, with the `tools` line
in names Copilot understands (recorded live with Copilot CLI 1.0.97: Claude's Bash and
mcp__<server> gave the role no shell and no MCP tools):
Read -> view; Grep / Glob -> grep / glob; Write / Edit -> create / edit; Bash / PowerShell ->
shell (powershell on Windows, bash elsewhere); Skill -> skill; Task / Agent -> task;
mcp__<server> -> <server>/*; mcp__<server>__<tool> -> <server>/<tool>. Copilot keeps `skills`
(it preloads them) and `model`; keys it does not know only warn. `effort` becomes Copilot's
reasoning-effort key, and every role gets `include-custom-instructions: true` (a subagent reads
CLAUDE.md / AGENTS.md only with it).
"""

import argparse
import os
import re
import sys

PLUGIN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# roles/: the original role files in a converted build such as the Gemini extension (KILN-REV-06)
SRC = os.path.join(PLUGIN, "roles") if os.path.isdir(os.path.join(PLUGIN, "roles")) else \
    os.path.join(PLUGIN, "agents")
OUT = os.path.join(PLUGIN, "copilot", "agents")
NAMES = {"Read": ["view"], "Grep": ["grep"], "Glob": ["glob"], "LS": ["glob"],
         "Write": ["create", "edit"], "Edit": ["edit"], "MultiEdit": ["edit"],
         "NotebookEdit": ["edit"], "Bash": ["shell"], "PowerShell": ["shell"],
         "Skill": ["skill"], "Task": ["task"], "Agent": ["task"], "WebFetch": ["web_fetch"]}
EFFORT_KEY = "reasoning-effort"  # the spelling Copilot applies (checked live, see CHANGELOG)
HEADER = ("<!-- Generated by scripts/copilot_agents.py from agents/{name} - edit the role there, "
          "then re-run the script. -->\n")


def copilot_tools(line):
    out = []
    for tool in (t.strip() for t in line.split(",")):
        if tool.startswith("mcp__"):
            parts = tool.split("__")
            names = [f"{parts[1]}/*"] if len(parts) == 2 else [f"{parts[1]}/{parts[2]}"]
        else:
            names = NAMES.get(tool, [])
        out += [n for n in names if n not in out]
    return ", ".join(out)


def convert(name, text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    head, body = m.group(1), text[m.end():]
    lines = []
    for line in head.splitlines():
        if line.startswith("tools:"):
            line = "tools: " + copilot_tools(line[len("tools:"):])
        elif line.startswith("disallowedTools:"):
            continue  # Claude-only names; the Kiln guard enforces the limits in Copilot too
        elif line.startswith("effort:"):
            line = EFFORT_KEY + ":" + line[len("effort:"):]  # Copilot ignores `effort`
        lines.append(line)
    # a role is a subagent: without this it gets no CLAUDE.md / AGENTS.md (Copilot 1.0.86+)
    lines.append("include-custom-instructions: true")
    return "---\n" + "\n".join(lines) + "\n---\n" + HEADER.format(name=name) + body


def build():
    return {fn: convert(fn, open(os.path.join(SRC, fn), encoding="utf-8").read())
            for fn in sorted(os.listdir(SRC)) if fn.endswith(".md")}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = build()
    if a.check:
        stale = []
        for fn, text in files.items():
            try:
                with open(os.path.join(OUT, fn), encoding="utf-8") as fh:
                    if fh.read() != text:
                        stale.append(fn)
            except OSError:
                stale.append(fn)
        extra = sorted(set(os.listdir(OUT)) - set(files)) if os.path.isdir(OUT) else []
        print(f"stale: {stale} extra: {extra}" if stale or extra else "copilot agents current")
        sys.exit(1 if stale or extra else 0)
    os.makedirs(OUT, exist_ok=True)
    for fn, text in files.items():
        with open(os.path.join(OUT, fn), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(f"wrote {len(files)} agents to {OUT}")


if __name__ == "__main__":
    main()
