"""Generate project-scope copies of Kiln roles with another reasoning effort (Python 3.12+, stdlib).

  python effort_agents.py [--project .] [--role modeler --effort medium]   # one copy
  python effort_agents.py [--project .] --from-tasks                       # every task with effort:
  python effort_agents.py [--project .] --clean                            # remove generated copies

Fallback for Claude Code CLIs whose Agent tool has no `effort` parameter (headless 2.1.281 lacked
it; 2.1.296 has it): a project agent `<role>-<effort>` is a copy of `kiln:<role>` with the
`effort:` line changed and its preloaded skills namespaced (`kiln:<skill>`), written to
`<project>/.claude/agents/<role>-<effort>.md`. Agents load when a session starts — generate them
BEFORE (re)starting the producer session, then delegate with `subagent_type: "<role>-<effort>"`.
`--from-tasks` reads `tasks/TASK-*.md` for `role:` and `effort:` lines. Generated files carry a
marker comment; `--clean` removes only those. Prints a JSON summary.
"""

import argparse
import glob
import json
import os
import re
import sys

PLUGIN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKER = "# generated by kiln scripts/effort_agents.py — delete after the task"
EFFORTS = {"low", "medium", "high", "xhigh", "max"}


def make_copy(project, role, effort):
    src = os.path.join(PLUGIN, "agents", f"{role}.md")
    if not os.path.isfile(src):
        raise ValueError(f"no Kiln role '{role}'")
    if effort not in EFFORTS:
        raise ValueError(f"effort must be one of {sorted(EFFORTS)}")
    text = open(src, encoding="utf-8").read()
    if not text.startswith("---"):
        raise ValueError(f"{src} has no frontmatter")
    _, fm, body = text.split("---", 2)
    lines, in_skills = [], False
    for line in fm.strip("\n").splitlines():
        if line.startswith("name:"):
            line = f"name: {role}-{effort}"
        elif line.startswith("effort:"):
            line = f"effort: {effort}"
        elif line.startswith("skills:"):
            in_skills = True
        elif in_skills and re.match(r"^\s+-\s+", line):
            skill = line.split("-", 1)[1].strip()
            line = f"  - {skill if ':' in skill else 'kiln:' + skill}"
        elif not line.startswith(" "):
            in_skills = False
        lines.append(line)
    if not any(l.startswith("effort:") for l in lines):
        lines.append(f"effort: {effort}")
    out = "---\n" + MARKER + "\n" + "\n".join(lines) + "\n---" + body
    dst_dir = os.path.join(project, ".claude", "agents")
    os.makedirs(dst_dir, exist_ok=True)
    dst = os.path.join(dst_dir, f"{role}-{effort}.md")
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(out)
    return dst


def from_tasks(project):
    pairs = set()
    for path in glob.glob(os.path.join(project, "tasks", "TASK-*.md")):
        text = open(path, encoding="utf-8").read()
        role = re.search(r"^role:\s*(?:kiln[:-])?([a-z0-9-]+)", text, re.M)
        effort = re.search(r"^effort:\s*([a-z]+)", text, re.M)
        if role and effort:
            pairs.add((role.group(1), effort.group(1)))
    return sorted(pairs)


def clean(project):
    removed = []
    for path in glob.glob(os.path.join(project, ".claude", "agents", "*.md")):
        if MARKER in open(path, encoding="utf-8").read():
            os.remove(path)
            removed.append(os.path.basename(path))
    return removed


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--project", default=".")
    ap.add_argument("--role")
    ap.add_argument("--effort")
    ap.add_argument("--from-tasks", action="store_true")
    ap.add_argument("--clean", action="store_true")
    a = ap.parse_args(argv)
    try:
        if a.clean:
            print(json.dumps({"removed": clean(a.project)}))
            return 0
        pairs = from_tasks(a.project) if a.from_tasks else [(a.role, a.effort)]
        if not pairs or None in pairs[0]:
            raise ValueError("give --role and --effort, or --from-tasks with tasks that set effort:")
        made = [os.path.relpath(make_copy(a.project, r, e), a.project) for r, e in pairs]
        print(json.dumps({"generated": made,
                          "delegate_as": [f"{r}-{e}" for r, e in pairs],
                          "note": "restart the producer session so it loads these agents"}))
        return 0
    except (OSError, ValueError) as exc:
        print(json.dumps({"error": str(exc)}))
        return 2


if __name__ == "__main__":
    sys.exit(main())
